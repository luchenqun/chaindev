export function translateRuntimeText(input: string, locale: Locale) {
  if (typeof input !== 'string') {
    return '';
  }

  if (locale === 'en') {
    return input;
  }

  return translateExactEnglishText(input) ?? translatePatternText(input) ?? input;
}

export function translateRuntimeAttribute(input: string, locale: Locale) {
  if (typeof input !== 'string') {
    return '';
  }

  if (locale === 'en') {
    return input;
  }

  return ATTRIBUTE_TRANSLATIONS[input] ?? translateRuntimeText(input, locale);
}
